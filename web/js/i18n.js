function getTimelineTickLabel(year) {
  const mobile =
    typeof window.tkkIsMobile === "function"
      ? window.tkkIsMobile()
      : window.matchMedia("(max-width: 768px)").matches;
  const map = {
    [-8000]: mobile ? "timeline.tick.8000bceShort" : "timeline.tick.8000bce",
    [-1000]: mobile ? "timeline.tick.1000bceShort" : "timeline.tick.1000bce",
    0: "timeline.tick.0",
    500: "timeline.tick.500ce",
    1000: "timeline.tick.1000ce",
    1500: "timeline.tick.1500ce",
    1800: "timeline.tick.1800ce",
  };
  if (year >= 2000) return t("timeline.tick.today");
  const k = map[year];
  return k ? t(k) : String(year);
}

